import { readFile, writeFile, unlink } from "node:fs/promises";
import { resolve, sep } from "node:path";

const root = resolve(import.meta.dirname, "..");
const dist = resolve(root, "dist");
const asset = async (path) => {
  const target = resolve(dist, path.replace(/^\.\//, ""));
  if (!target.startsWith(dist + sep))
    throw new Error(`Asset is outside dist: ${path}`);
  return readFile(target, "utf8");
};
let html = await readFile(resolve(dist, "app.html"), "utf8");
const script = html.match(/<script\b[^>]*\bsrc="([^"]+)"[^>]*><\/script>/);
const stylesheet = html.match(
  /<link\b[^>]*\brel="stylesheet"[^>]*\bhref="([^"]+)"[^>]*>/,
);
if (!script || !stylesheet)
  throw new Error("Expected one compiled script and stylesheet.");
const js = (await asset(script[1])).replace(/<\/script/gi, "<\\/script");
const css = (await asset(stylesheet[1])).replace(/<\/style/gi, "<\\/style");
if (/@import\b|url\(\s*["']?https?:/i.test(css))
  throw new Error(
    "The portable stylesheet must not depend on external assets.",
  );
// Use a classic inline script: ES modules and fetch-based assets are restricted
// on file:// URLs. React's production IIFE needs no external runtime files.
html = html
  .replace(script[0], "")
  .replace(stylesheet[0], () => `<style>${css}</style>`);
html = html.replace("</body>", () => `<script>${js}</script>\n</body>`);
html = html.replace(
  "<!doctype html>",
  "<!doctype html>\n<!-- Generated by npm run build. Edit app.html and src/, then rebuild. -->",
);
html = html.replace(/^[\t ]+$/gm, "");
await Promise.all([
  writeFile(resolve(root, "index.html"), html),
  writeFile(resolve(dist, "index.html"), html),
]);
await unlink(resolve(dist, "app.html"));
console.log(
  "Created self-contained index.html in the project root and dist/. Open either file directly — no server or installation needed.",
);
